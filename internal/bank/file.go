package bank

import (
	"encoding/json"
	"os"
	"path/filepath"
)

// SaveSecret writes v as JSON readable.
func SaveSecret(path string, v any) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	// using a temp file so a crash never leaves a half-written secret
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, b, 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// LoadSecret reads a file written by SaveSecret. Expect `os.ErrNotExist`.
func LoadSecret(path string, v any) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	return json.Unmarshal(b, v)
}
